package net.cumba.sasutils.xpt;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;
import net.cumba.sasutils.Observation;
import org.junit.jupiter.api.Test;

/**
 * A NAMESTR record's two padding fields carry no data, so the reader must accept whatever bytes a
 * writer leaves in them.
 *
 * <p>
 * Oracle: the XPORT v5 record layout (TS-140) declares them {@code char nfill[2]}, commented
 * "UNUSED, FOR ALIGNMENT AND FUTURE", and {@code char rest[52]}, commented "remaining fields are
 * irrelevant". Requiring zero bytes there refused real transport files: every
 * {@code phuse-scripts/send_1/xpt} file has two ASCII blanks in {@code nfill}
 * ({@code ConstantMismatchException "Token 10 Expected 0000 found 2020"}). The expected names,
 * labels, positions and cell values are the ones ReadStat reports for the same files (pyreadstat
 * 1.3.3 {@code read_xport}), not this reader's own output.
 * </p>
 *
 * <p>
 * Each field has a fixture only it can fail on: {@code phuse_send_1_bg.xpt} has blank {@code nfill}
 * and zero {@code rest}; {@code namestr_blank_rest_3x3.xpt} (generated by the script beside it) has
 * zero {@code nfill} and blank {@code rest}. The positions and the informat fields are asserted
 * because they are the fields read right after the padding: a padding token of the wrong length
 * would shift them.
 * </p>
 */
class VariableXptPaddingTest
{

    private static File fixture(String aName)
    {
        return new File(System.getProperty("projectBasedir"),
                "src/test/resources/net/cumba/sasutils/xpt/namestr-padding/" + aName);
    }


    @Test
    void blankNfillIsReadLikeZeroNfill() throws IOException
    {
        LibraryXpt library = new ParserXpt().parseLibrary(fixture("phuse_send_1_bg.xpt"));

        assertEquals(1, library.getDatasets().size());
        DatasetXpt bg = library.getDatasets().get(0);
        assertEquals("BG", bg.getName());

        List<VariableXpt> vars = bg.getVariables();
        assertEquals(List.of("STUDYID", "DOMAIN", "USUBJID", "BGSEQ", "BGTESTCD", "BGTEST",
                "BGORRES", "BGORRESU", "BGSTRESC", "BGSTRESN", "BGSTRESU", "BGDTC", "BGENDTC",
                "BGDY", "BGENDY"), vars.stream().map(VariableXpt::getName).toList());
        assertEquals(
                List.of("Study Identifier", "Domain Abbreviation", "Unique Subject Identifier",
                        "Sequence Number", "Test Short Name", "Test Name",
                        "Result or Findings as Collected", "Unit of the Original Result",
                        "Standardized Result in Character Format",
                        "Standardized Result in Numeric Format", "Unit of the Standardized Result",
                        "Date/Time Animal Weighed", "End Date/Time Animal Weighed",
                        "Study Day of Start of Interval", "Study Day of End of Weight Interval"),
                vars.stream().map(VariableXpt::getLabel).toList());
        assertEquals(List.of(0, 7, 9, 23, 31, 37, 53, 57, 59, 63, 71, 73, 92, 111, 119),
                vars.stream().map(VariableXpt::getPosition).toList());

        List<List<Object>> rows = rows(bg);
        assertEquals(40, rows.size());
        assertEquals(List.of("8326556", "BG", "8326556-I10808", 1.0d, "BWGAIN", "Body Weight Gain",
                "0.0", "kg", "0.0", 0.0d, "kg", "2015-07-23T14:56:21", "2015-07-30T08:08:31", -8.0d,
                -1.0d), rows.get(0));
        assertEquals(List.of("8326556", "BG", "8326556-I10808", 9.0d, "BWGAIN", "Body Weight Gain",
                "-0.2", "kg", "-0.2", -0.2d, "kg", "2015-09-11T07:06:27", "2015-09-18T07:11:41",
                43.0d, 50.0d), rows.get(8));
        assertEquals(List.of("8326556", "BG", "8326556-I10811", 40.0d, "BWGAIN", "Body Weight Gain",
                "0.0", "kg", "0.0", 0.0d, "kg", "2015-09-18T07:21:39", "2015-09-25T07:09:03", 50.0d,
                57.0d), rows.get(39));
    }


    @Test
    void blankRestIsReadLikeZeroRest() throws IOException
    {
        LibraryXpt library = new ParserXpt().parseLibrary(fixture("namestr_blank_rest_3x3.xpt"));

        assertEquals(1, library.getDatasets().size());
        DatasetXpt ds = library.getDatasets().get(0);
        assertEquals("BLANKRST", ds.getName());

        List<VariableXpt> vars = ds.getVariables();
        assertEquals(List.of("USUBJID", "AGE", "WEIGHT"),
                vars.stream().map(VariableXpt::getName).toList());
        assertEquals(List.of("Unique Subject Identifier", "Age", "Weight (kg)"),
                vars.stream().map(VariableXpt::getLabel).toList());
        assertEquals(List.of("$", "BEST", ""),
                vars.stream().map(VariableXpt::getFormatTypeString).toList());
        assertEquals(List.of((short) 8, (short) 8, (short) 8),
                vars.stream().map(VariableXpt::getFormatLength).toList());
        assertEquals(List.of((short) 0, (short) 0, (short) 1),
                vars.stream().map(VariableXpt::getFormatDecimals).toList());
        assertEquals(List.of("$", "BEST", ""),
                vars.stream().map(VariableXpt::getInformatTypeString).toList());
        assertEquals(List.of((short) 8, (short) 8, (short) 0),
                vars.stream().map(VariableXpt::getInformatLength).toList());
        assertEquals(List.of(0, 8, 16), vars.stream().map(VariableXpt::getPosition).toList());

        List<List<Object>> rows = rows(ds);
        assertEquals(List.of(List.of("SUBJ-001", 34.0d, 70.5d), List.of("SUBJ-002", 61.0d, 82.25d),
                List.of("SUBJ-003", 47.0d, 0.0d)), rows);
    }

    // ------------------------------------------------------------------ helpers


    private static List<List<Object>> rows(DatasetXpt aDataset) throws IOException
    {
        List<List<Object>> rows = new ArrayList<>();
        try (Stream<Observation> stream = aDataset.streamObservations())
        {
            stream.forEach(o -> rows.add(o.getValues().values().stream()
                    .map(v -> v instanceof String s ? (Object) s.strip() : v).toList()));
        }
        return rows;
    }
}
